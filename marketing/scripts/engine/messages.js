function getInitial(name, category = '') {
  const cat = (category || '').toLowerCase();
  let pool;
  if (['doctor','dentist','medical','health','physio','optom','vet','clinic','pharmacy','specialist'].some(c => cat.includes(c))) {
    pool = [...INITIAL.medical, ...INITIAL.default];
  } else if (['lawyer','attorney','legal','law','advocate'].some(c => cat.includes(c))) {
    pool = [...INITIAL.legal, ...INITIAL.default];
  } else if (['plumber','electrician','builder','construct','roofer','painter','tiler','carpenter','pest','locksmith','handyman'].some(c => cat.includes(c))) {
    pool = [...INITIAL.trades, ...INITIAL.default];
  } else if (['restaurant','cafe','takeaway','catering','bakery','butcher','food'].some(c => cat.includes(c))) {
    pool = [...INITIAL.restaurant, ...INITIAL.default];
  } else if (['salon','hair','beauty','nail','spa','barber','grooming'].some(c => cat.includes(c))) {
    pool = [...INITIAL.beauty, ...INITIAL.default];
  } else if (['mechanic','panel','tyre','car wash','auto','motor'].some(c => cat.includes(c))) {
    pool = [...INITIAL.automotive, ...INITIAL.default];
  } else {
    pool = INITIAL.default;
  }
  return pool[Math.floor(Math.random() * pool.length)](name);
}

